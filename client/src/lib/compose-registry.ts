/** Lookup an option by its registry key. */
export function findOption(key: string): OptionEntry | undefined {
  return COMPOSE_REGISTRY.find((o) => o.key === key);
}

/** All option keys registered. */
export const REGISTRY_KEYS = COMPOSE_REGISTRY.map((o) => o.key);
