export type OptionMeta = {
  key: string; // e.g. "services.*.restart"
  label: string;
  type: "string" | "number" | "boolean" | "enum" | "list" | "map";
  description: string;
  whenToUse: string;
  ifUsed: string;
  ifOmitted: string;
  example: string;
  defaultValue?: string;
  riskLevel?: "none" | "low" | "medium" | "high";
  riskNote?: string;
  docsUrl?: string;
};

export type OptionCategory =
  | "Basic"
  | "Networking"
  | "Storage"
  | "Health"
  | "Resources"
  | "Security"
  | "Advanced";

export interface OptionEntry extends OptionMeta {
  category: OptionCategory;
}

